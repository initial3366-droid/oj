// Real browser + local HTTP backend + MySQL. Run verify-polygon-contests.py first for fixture ZIPs.
import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || '/tmp/qoj-practice-browser/node_modules/playwright/index.mjs');
const env = Object.fromEntries((await fs.readFile('.env', 'utf8')).split('\n').filter(s => s.includes('=') && !s.startsWith('#')).map(s => { const i = s.indexOf('='); return [s.slice(0, i).trim(), s.slice(i + 1).trim().replace(/^["']|["']$/g, '')]; }));
const b64 = value => Buffer.from(JSON.stringify(value)).toString('base64url');
const encoded = b64({ alg: 'HS256', typ: 'JWT' }) + '.' + b64({ sub: '1', jti: crypto.randomUUID(), typ: 'access', accountType: 'ADMIN', iat: Math.floor(Date.now() / 1000), exp: Math.floor(Date.now() / 1000) + 600 });
const token = encoded + '.' + crypto.createHmac('sha256', env.JWT_SECRET || 'change-this-secret-to-at-least-32-bytes').update(encoded).digest('base64url');
const prefix = env.VITE_ADMIN_PREFIX || 'auth_ac';
const api = env.ADMIN_API_PREFIX || `/api/${prefix}/v1`;
const base = process.env.POLYGON_BROWSER_BASE_URL || 'http://127.0.0.1:5173';
const out = '.runtime/polygon-e2e';
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH || '/Users/initial/Library/Caches/ms-playwright/chromium-1243/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing' });
const context = await browser.newContext({ viewport: { width: 1680, height: 1150 } });
// Trace excludes network: a real short-lived admin token must not enter artifacts.
await context.addInitScript(token => sessionStorage.setItem('qoj.adminAccessToken', token), token);
const page = await context.newPage();
page.setDefaultTimeout(15000);
const checks = [], errors = [];
let contestId, problemIds = [];
page.on('pageerror', e => errors.push(e.message));
try {
  await page.goto(`${base}/${prefix}/contests`);
  await page.getByRole('button', { name: '导入 Polygon', exact: true }).click();
  const modal = page.getByRole('dialog');
  const doImport = modal.getByRole('button', { name: '导入为新比赛' });
  assert.equal(await doImport.isDisabled(), true);
  await modal.getByLabel('Polygon ZIP 文件').setInputFiles(`${out}/contest.zip`);
  await modal.getByRole('button', { name: '预览包内容' }).click();
  await modal.getByText('已识别 2 道题目', { exact: false }).waitFor();
  await page.waitForFunction(() => Array.from(document.querySelectorAll('button')).some(b => b.textContent.trim() === '预览包内容' && !b.disabled));
  assert.ok((await modal.innerText()).includes('求和与空白'));
  await page.screenshot({ path: `${out}/import-preview.png`, fullPage: true });
  checks.push('比赛列表入口、先预览后导入、题目与测试概览');
  await modal.getByLabel('Polygon 比赛名称').fill('Polygon browser E2E ' + Date.now());
  const date = modal.locator('.arco-picker input');
  await date.fill('2030-01-01 09:00:00');
  await date.press('Enter');
  await modal.getByText('比赛名称', { exact: true }).click();
  const result = page.waitForResponse(r => r.url().endsWith('/polygon/import'));
  await doImport.click();
  const response = await result;
  const body = await response.json();
  assert.equal(response.status(), 200, body.message);
  contestId = body.data.contestId;
  await page.waitForURL(`**/contests/${contestId}/edit`);
  checks.push('真实上传和创建后进入比赛编辑页');
  const detail = await context.request.get(`${base}${api}/contests/${contestId}`, { headers: { Authorization: `Bearer ${token}` } });
  problemIds = (await detail.json()).data.problems.map(p => p.problemId);
  await page.goto(`${base}/${prefix}/contests`);
  const row = page.locator('tr').filter({ hasText: 'Polygon browser E2E' }).first();
  const downloadPromise = page.waitForEvent('download');
  await row.getByRole('button', { name: '导出 Polygon', exact: true }).click();
  const download = await downloadPromise;
  await download.saveAs(`${out}/browser-export.zip`);
  assert.ok((await fs.stat(`${out}/browser-export.zip`)).size > 1000);
  checks.push('比赛列表导出下载真实 ZIP 文件');
  await page.screenshot({ path: `${out}/contest-list.png`, fullPage: true });
  await page.getByRole('button', { name: '导入 Polygon', exact: true }).click();
  await modal.getByLabel('Polygon ZIP 文件').setInputFiles(`${out}/single.zip`);
  await modal.getByRole('button', { name: '预览包内容' }).click();
  await modal.getByText('已识别 1 道题目', { exact: false }).waitFor();
  await modal.getByLabel('Polygon ZIP 文件').setInputFiles(`${out}/contest.zip`);
  assert.equal(await doImport.isDisabled(), true);
  checks.push('切换文件清空旧预览，必须重新预览');
  assert.deepEqual(errors, []);
} catch (e) {
  errors.push(e.stack || e.message);
  process.exitCode = 1;
  await page.screenshot({ path: `${out}/browser-failure.png`, fullPage: true });
} finally {
  const headers = { Authorization: `Bearer ${token}` };
  if (contestId) await context.request.delete(`${base}${api}/contests/${contestId}`, { headers });
  for (const id of problemIds) await context.request.delete(`${base}${api}/problems/${id}`, { headers });
  await fs.writeFile(`${out}/browser-report.json`, JSON.stringify({ passed: errors.length === 0, checks, errors }, null, 2));
  await browser.close();
  console.log(JSON.stringify({ checks, errors }));
}
